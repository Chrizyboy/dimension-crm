-- Rechnungen & Finanzen (Modul-Prüfung 25A): weniger Auslösen von Hand.
-- 1. Abgleich AbaNinja jede Nacht durch den Zeitplan (Zahlungen, Lieferantenrechnungen), nicht nur auf Klick.
-- 2. «Heute prüfen»: eine Abfrage für Entwürfe, wartende Mahnungen im Ausgangskorb und neu erkannte Zahlungen.
-- 3. Erinnerungen als Glocke: montags ab 07:00 die wartenden Mahnungen (Mahnlauf), am Monatsanfang offene Spesen.
-- 4. Rate bei Montage als Entwurf (nicht die letzte Tranche); Wartungsrechnung als Vorlage (aus, bis die Buchhaltung
--    entscheidet, ob Wartungen im Voraus verrechnet werden).

-- Reihenfolge der Tranchen, wie sie angelegt wurden: bei gleichem Betrag ohne Datum (30/30) entscheidet sie, welche
-- die letzte ist. Bestehende Zeilen bekommen sie in der Reihenfolge der Ablage.
alter table public.zahlungsplan add column if not exists reihenfolge bigint generated by default as identity;

create or replace function public.abaninja_abgleich_anwenden(p jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO ''
AS $function$
declare
  x jsonb;
  r public.rechnungen;
  v_diff bigint;
  v_heute date := (now() at time zone 'Europe/Zurich')::date;
  n_re int := 0; n_za int := 0; n_be int := 0; n_zu int := 0;
  v_projekt uuid;
  v_id uuid;
begin
  -- Der Zeitplan gleicht jede Nacht ab (Dienst-Rolle); aus der App nur mit Recht «finanzen».
  if not (intern.hat_recht('finanzen') or coalesce(auth.role(), '') = 'service_role') then raise exception using errcode = 'P0001', message = 'finanzen.kein_recht'; end if;
  for x in select * from jsonb_array_elements(coalesce(p -> 'rechnungen', '[]')) loop
    select * into r from public.rechnungen
     where geloescht_am is null and (abaninja_uuid = x ->> 'uuid' or (abaninja_uuid is null and nummer = x ->> 'reference'))
     limit 1;
    continue when not found;
    n_re := n_re + 1;
    update public.rechnungen set abaninja_uuid = x ->> 'uuid', abaninja_nummer = coalesce(x ->> 'nummer', abaninja_nummer),
           abaninja_status = x ->> 'status', abaninja_offen_rappen = (x ->> 'offen_rappen')::bigint, abaninja_abgeglichen_am = now()
     where id = r.id;
    if r.status in ('gestellt', 'teilbezahlt') and x ? 'offen_rappen' then
      v_diff := (r.total_rappen - (x ->> 'offen_rappen')::bigint) - r.bezahlt_rappen;
      if v_diff > 0 then
        insert into public.rechnung_zahlungen (rechnung_id, datum, betrag_rappen, quelle, notiz)
        values (r.id, v_heute, v_diff, 'abaninja', 'Abgleich AbaNinja');
        n_za := n_za + 1;
      end if;
    end if;
  end loop;

  for x in select * from jsonb_array_elements(coalesce(p -> 'belege', '[]')) loop
    -- Projekt aus Referenz oder Titel: Projektnummer (6 Ziffern) oder Bestellnummer (B0026).
    select coalesce(
      (select pr.id from public.projekte pr where pr.geloescht_am is null and pr.nummer <> ''
          and (coalesce(x ->> 'reference', '') || ' ' || coalesce(x ->> 'titel', '')) ~ ('\m' || pr.nummer || '\M') limit 1),
      (select b.projekt_id from public.bestellungen b where b.geloescht_am is null and b.projekt_id is not null
          and (coalesce(x ->> 'reference', '') || ' ' || coalesce(x ->> 'titel', '')) ~* ('\m' || b.nummer || '\M') limit 1))
      into v_projekt;
    select id into v_id from public.kreditor_zahlungen where abaninja_uuid = x ->> 'uuid';
    if v_id is null then
      insert into public.kreditor_zahlungen (abaninja_uuid, firma, text, kategorie, rechnung_nr, rechnung_am, betrag_rappen,
                                             faellig_am, prioritaet, status, quelle, projekt_id, offen_rappen, bezahlt_am,
                                             lieferant_id)
      values (x ->> 'uuid', x ->> 'lieferant', coalesce(nullif(x ->> 'titel', ''), x ->> 'reference'),
              case when v_projekt is not null then 'Lieferant' end, coalesce(x ->> 'nummer', x ->> 'reference'),
              nullif(x ->> 'datum', '')::date, (x ->> 'total_rappen')::bigint, nullif(x ->> 'faellig_am', '')::date,
              'normal', case when (x ->> 'storniert')::boolean then 'storniert'
                             when (x ->> 'offen_rappen')::bigint = 0 then 'bezahlt' else 'offen' end,
              'abaninja', v_projekt, (x ->> 'offen_rappen')::bigint,
              case when (x ->> 'offen_rappen')::bigint = 0 then v_heute end,
              (select l.id from public.lieferanten l where l.geloescht_am is null and lower(l.name) = lower(x ->> 'lieferant') limit 1));
      n_be := n_be + 1;
      if v_projekt is not null then n_zu := n_zu + 1; end if;
    else
      update public.kreditor_zahlungen set
        betrag_rappen = (x ->> 'total_rappen')::bigint, offen_rappen = (x ->> 'offen_rappen')::bigint,
        faellig_am = coalesce(nullif(x ->> 'faellig_am', '')::date, faellig_am),
        status = case when (x ->> 'storniert')::boolean then 'storniert'
                      when (x ->> 'offen_rappen')::bigint = 0 then 'bezahlt' else status end,
        bezahlt_am = case when (x ->> 'offen_rappen')::bigint = 0 then coalesce(bezahlt_am, v_heute) end,
        projekt_id = coalesce(projekt_id, v_projekt)
      where id = v_id;
    end if;
  end loop;
  return jsonb_build_object('rechnungen', n_re, 'zahlungen', n_za, 'belege_neu', n_be, 'belege_zugeordnet', n_zu);
end
$function$;

create or replace function intern.automation_aktion(a public.automationen, l public.automation_laeufe, nr integer, x jsonb, ctx jsonb, p_als uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  art text := x ->> 'art';
  ids uuid[];
  n int;
  v_heute date := (now() at time zone 'Europe/Zurich')::date;
  v_id uuid;
  v_plz text;
  v_std uuid;
begin
  if art in ('aufgabe', 'benachrichtigung', 'dubletten', 'zielgruppe') then
    ids := intern.automation_empfaenger(coalesce(x -> 'an', '["zustaendig"]'), ctx);
    if coalesce(cardinality(ids), 0) = 0 then
      return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', 'kein_empfaenger');
    end if;
  end if;

  if art = 'aufgabe' then
    insert into public.aufgaben (titel, text, faellig_am, person_id, bezug_tabelle, bezug_id, lauf_id)
    select intern.automation_text(intern.zweisprachig(x -> 'titel', coalesce(p.sprache, 'de')), ctx),
           nullif(intern.automation_text(intern.zweisprachig(x -> 'text', coalesce(p.sprache, 'de')), ctx), ''),
           v_heute + coalesce((x ->> 'faellig_tage')::int, 0), p.id, l.tabelle, l.bezug_id, l.id
      from public.personen p where p.id = any (ids);
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'aufgabe',
                              'werte', jsonb_build_object('an', intern.personen_namen(ids)), 'ziel', '/tasks');

  elsif art = 'benachrichtigung' then
    n := intern.automation_melden(ids, x ->> 'stufe', x -> 'titel', x -> 'text', ctx, ctx ->> 'ziel', l.id);
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'benachrichtigt',
                              'werte', jsonb_build_object('an', intern.personen_namen(ids)));

  elsif art in ('mail', 'sms', 'zahlungserinnerung') then
    return intern.automation_nach_aussen(a, l, nr, x, ctx, p_als);

  elsif art = 'dubletten' then
    select count(*) into n from public.moegliche_dubletten(ctx #>> '{kontakt,name}', ctx #>> '{kontakt,email}',
                                                          ctx #>> '{kontakt,telefon}', (ctx #>> '{kontakt,id}')::uuid);
    if n = 0 then return jsonb_build_object('ergebnis', 'ok', 'meldung', 'keine_dublette'); end if;
    perform intern.automation_melden(ids, 'warnung',
      jsonb_build_object('de', 'Mögliche Dublette: {Name}', 'fr', 'Doublon possible : {Name}'),
      jsonb_build_object('de', n || ' ähnliche Kontakte gefunden. Bitte prüfen und zusammenführen.',
                         'fr', n || ' contacts similaires trouvés. Merci de vérifier et fusionner.'),
      ctx, intern.automation_ziel('kontakte', (ctx #>> '{kontakt,id}')::uuid), l.id);
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'dublette', 'werte', jsonb_build_object('anzahl', n),
                              'ziel', intern.automation_ziel('kontakte', (ctx #>> '{kontakt,id}')::uuid));

  elsif art = 'zuteilen' then
    if l.tabelle <> 'verkaufschancen' then
      return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', 'nur_leads');
    end if;
    if nullif(ctx #>> '{standort,id}', '') is not null then
      return jsonb_build_object('ergebnis', 'ok', 'meldung', 'schon_zugeteilt', 'werte', jsonb_build_object('standort', ctx #>> '{standort,name}'));
    end if;
    v_plz := ctx #>> '{lead,plz}';
    select s.id into v_std from public.standorte s where s.kuerzel = public.standort_fuer_plz(v_plz) and s.geloescht_am is null;
    if v_std is null then
      return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', 'keine_plz');
    end if;
    update public.verkaufschancen set standort_id = v_std where id = l.bezug_id;
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'zugeteilt',
                              'werte', jsonb_build_object('standort', (select name from public.standorte where id = v_std)));

  elsif art = 'rechnung_entwurf' and l.tabelle in ('rapporte', 'wartungsvertraege') then
    if l.tabelle = 'rapporte' and coalesce(ctx #>> '{rapport,verrechnung}', '') <> 'kostenpflichtig' then
      return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', 'nicht_verrechenbar');
    end if;
    begin
      v_id := public.rechnung_entwurf(case when l.tabelle = 'rapporte' then jsonb_build_object('rapport_id', l.bezug_id)
                                           else jsonb_build_object('wartungsvertrag_id', l.bezug_id) end);
    exception when others then
      if sqlerrm in ('finanzen.schon_verrechnet', 'finanzen.rapport_nicht_verrechenbar') then
        return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', replace(sqlerrm, 'finanzen.', ''));
      end if;
      raise;
    end;
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'rechnung_entwurf',
                              'ziel', intern.automation_ziel('rechnungen', v_id));

  elsif art = 'rechnung_entwurf' then
    select z.id into v_id from public.zahlungsplan z
     where z.projekt_id = coalesce(case when l.tabelle = 'projekte' then l.bezug_id end,
                                   (select r.projekt_id from public.rechnungen r where r.id = l.bezug_id))
       and z.geloescht_am is null
       and not exists (select 1 from public.rechnungen r where r.zahlungsplan_id = z.id and r.geloescht_am is null
                                                         and r.status <> 'storniert')
       -- «nicht_letzte»: Rate bei Montage; die letzte Tranche bleibt für die Schlussrechnung nach der IBN.
       and (x ->> 'tranche' is distinct from 'nicht_letzte'
            or z.id <> (select z2.id from public.zahlungsplan z2 where z2.projekt_id = z.projekt_id and z2.geloescht_am is null
                         order by z2.faellig_am desc nulls first, z2.betrag_rappen, z2.reihenfolge desc limit 1))
     order by case when x ->> 'tranche' = 'letzte' then 0 end,
              case when x ->> 'tranche' = 'letzte' then z.faellig_am end desc nulls first,
              case when x ->> 'tranche' = 'letzte' then z.betrag_rappen end,
              case when x ->> 'tranche' = 'letzte' then z.reihenfolge end desc,
              z.faellig_am nulls last, z.betrag_rappen desc, z.reihenfolge
     limit 1;
    if v_id is null then
      return jsonb_build_object('ergebnis', 'uebersprungen', 'meldung', 'keine_tranche');
    end if;
    v_id := public.rechnung_entwurf(jsonb_build_object('zahlungsplan_id', v_id));
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'rechnung_entwurf',
                              'ziel', intern.automation_ziel('rechnungen', v_id));

  elsif art = 'zielgruppe' then
    select count(*) into n from public.marketing_zielgruppe z
     where z.gruppe = 'kunde' and not z.werbesperre
       and case x ->> 'merkmal'
             when 'ohne_batterie' then not coalesce(z.batterie, false)
             when 'ohne_wallbox' then not coalesce(z.wallbox, false)
             when 'ohne_waermepumpe' then not coalesce(z.waermepumpe, false)
             when 'alt' then z.anlage_seit <= v_heute - interval '3 years'
             else false end;
    if n = 0 then return jsonb_build_object('ergebnis', 'ok', 'meldung', 'zielgruppe_leer'); end if;
    perform intern.automation_melden(ids, 'info', x -> 'titel',
      jsonb_build_object('de', n || ' Kunden passen. Zielgruppe öffnen und anschreiben.',
                         'fr', n || ' clients correspondent. Ouvrir le groupe cible et écrire.'),
      ctx, '/marketing?ansicht=anschreiben&anlage=' || (x ->> 'merkmal'), l.id);
    return jsonb_build_object('ergebnis', 'ok', 'meldung', 'zielgruppe',
                              'werte', jsonb_build_object('anzahl', n, 'an', intern.personen_namen(ids)),
                              'ziel', '/marketing?ansicht=anschreiben&anlage=' || (x ->> 'merkmal'));
  end if;
  raise exception using errcode = 'P0001', message = 'automation.aktion_unbekannt';
end
$function$;

/**
 * «Heute prüfen» der Buchhaltung: Entwürfe, Mahnungen und Zahlungserinnerungen, die im Ausgangskorb auf Freigabe
 * warten, und Zahlungen der letzten 14 Tage aus dem Abgleich. Nur mit Recht «finanzen».
 */
create or replace function public.rechnungen_heute() returns jsonb
language plpgsql stable security invoker set search_path = '' as $$
begin
  if not intern.hat_recht('finanzen') then raise exception using errcode = 'P0001', message = 'finanzen.kein_recht'; end if;
  return jsonb_build_object(
    'entwuerfe', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'art', r.art, 'titel', r.titel, 'kunde', r.kunde,
                                                               'projekt_nummer', r.projekt_nummer, 'total_rappen', r.total_rappen,
                                                               'erstellt_am', r.erstellt_am) order by r.erstellt_am)
                             from public.rechnungen_liste r where r.status = 'entwurf'), '[]'),
    'mahnungen', coalesce((select jsonb_agg(jsonb_build_object('id', a.id, 'rechnung_id', a.bezug_id, 'betreff', a.betreff,
                                                               'an', a.an, 'erstellt_am', a.erstellt_am, 'status', a.status,
                                                               'nummer', r.nummer, 'kunde', r.kunde, 'offen_rappen', r.offen_rappen,
                                                               'mahnstufe', r.mahnstufe) order by a.erstellt_am)
                             from public.ausgangskorb a
                             left join public.rechnungen_liste r on r.id = a.bezug_id
                            where a.geloescht_am is null and a.art = 'mahnung' and a.status in ('wartet', 'fehler')), '[]'),
    'zahlungen', coalesce((select jsonb_agg(jsonb_build_object('id', z.id, 'rechnung_id', z.rechnung_id, 'datum', z.datum,
                                                               'betrag_rappen', z.betrag_rappen, 'quelle', z.quelle,
                                                               'nummer', r.nummer, 'kunde', r.kunde, 'status', r.status)
                                            order by z.datum desc, z.erstellt_am desc)
                             from public.rechnung_zahlungen z join public.rechnungen_liste r on r.id = z.rechnung_id
                            where z.geloescht_am is null and z.datum >= (now() at time zone 'Europe/Zurich')::date - 14), '[]'));
end
$$;

/** Personen mit einer Rolle oder dem Recht «finanzen»/«admin» (für die Glocke der Buchhaltung). */
create or replace function intern.buchhaltung_personen() returns uuid[]
language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(p.id), '{}') from public.personen p left join public.rollen r on r.schluessel = p.rolle
   where p.aktiv and p.geloescht_am is null
     and (p.rolle = 'buchhaltung' or 'finanzen' = any (p.rechte) or 'finanzen' = any (coalesce(r.rechte, '{}')))
$$;

/**
 * Zeitplan (stündlich): montags ab 07:00 eine Glocke «Mahnlauf» mit der Zahl der wartenden Mahnungen; am 1. des
 * Monats eine Glocke «Spesen auszahlen» mit Anzahl und Summe. Je Woche bzw. Monat höchstens einmal. Nur intern.
 */
create or replace function public.finanzen_erinnern() returns int
language plpgsql security definer set search_path = '' as $$
declare
  jetzt timestamp := now() at time zone 'Europe/Zurich';
  n int := 0;
  anzahl int;
  summe bigint;
  wer uuid[] := intern.buchhaltung_personen();
begin
  if extract(isodow from jetzt) = 1 and jetzt::time >= '07:00'
     and not exists (select 1 from public.benachrichtigungen b where b.titel_de like 'Mahnlauf:%'
                       and b.erstellt_am >= date_trunc('week', jetzt) at time zone 'Europe/Zurich') then
    select count(*) into anzahl from public.ausgangskorb a
     where a.geloescht_am is null and a.art = 'mahnung' and a.status in ('wartet', 'fehler');
    if anzahl > 0 then
      insert into public.benachrichtigungen (person_id, art, titel_de, titel_fr, text_de, text_fr, ziel)
      select x, 'info', 'Mahnlauf: ' || anzahl || ' Mahnungen warten', 'Relances : ' || anzahl || ' en attente',
             'Unter Rechnungen › Heute prüfen mit einem Klick freigeben.', 'À valider en un clic sous Factures › À vérifier.',
             '/invoices?reiter=heute'
        from unnest(wer) x;
      n := n + 1;
    end if;
  end if;
  if extract(day from jetzt) = 1
     and not exists (select 1 from public.benachrichtigungen b where b.titel_de like 'Spesen auszahlen:%'
                       and b.erstellt_am >= date_trunc('month', jetzt) at time zone 'Europe/Zurich') then
    select count(*), coalesce(sum(betrag_rappen), 0) into anzahl, summe from public.spesen
     where geloescht_am is null and status = 'eingereicht';
    if anzahl > 0 then
      insert into public.benachrichtigungen (person_id, art, titel_de, titel_fr, text_de, text_fr, ziel)
      select x, 'info', 'Spesen auszahlen: ' || anzahl || ' offen', 'Frais à payer : ' || anzahl || ' ouverts',
             'Total ' || intern.chf_text(summe) || '. Auszahlen und Belege an die Buchhaltung senden.',
             'Total ' || intern.chf_text(summe) || '. Payer et envoyer les justificatifs à la comptabilité.',
             '/expenses'
        from unnest(wer) x;
      n := n + 1;
    end if;
  end if;
  return n;
end
$$;

